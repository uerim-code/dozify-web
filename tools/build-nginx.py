#!/usr/bin/env python3
"""Render deploy/nginx.conf from vercel.json + the PAGES map.

The site moved from Vercel to Coolify's static nginx (nginx:alpine) and none
of vercel.json carried over: no clean URLs beyond try_files, no redirects, no
security headers, and the hand-edited root sources (bilingual index.html,
/tools, /docs) were served as-is. This keeps one source of truth: vercel.json
still defines the redirects and headers, this script translates them, and the
result is pasted into the Coolify app's "custom nginx configuration"
(tools/deploy-nginx.sh does that through the API).

Run after build-languages.py (which rewrites the CSP hash in vercel.json).
"""
import importlib.util
import json
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "deploy" / "nginx.conf"

spec = importlib.util.spec_from_file_location("bl", ROOT / "tools" / "build-languages.py")
bl = importlib.util.module_from_spec(spec)
spec.loader.exec_module(bl)

sys.path.insert(0, str(ROOT / "tools"))
from i18n_common import LANGS, has  # noqa: E402

vercel = json.loads((ROOT / "vercel.json").read_text(encoding="utf-8"))


def exact_redirects() -> dict[str, tuple[str, int]]:
    """source path -> (destination, status). Root sources and their .html twins
    all point at the generated /en page, so nothing bilingual is ever served."""
    out: dict[str, tuple[str, int]] = {}
    for r in vercel.get("redirects", []):
        if r["source"] == "/" or r.get("has"):
            continue
        out[r["source"]] = (r["destination"], 301 if r.get("permanent") else 302)
    for src, (en, _tr) in bl.PAGES.items():
        dest = f"/en/{en}" if en else "/en"
        stem = "/" + src[: -len(".html")]
        for path in (stem, "/" + src):
            if path.endswith("/index"):
                path = path[: -len("/index")] or "/"
            if path != "/":
                out.setdefault(path, (dest, 301))
    out.pop("/index.html", None)
    out["/index.html"] = ("/en", 301)
    return dict(sorted(out.items()))


def headers() -> list[tuple[str, str]]:
    for block in vercel.get("headers", []):
        if block.get("source") == "/(.*)":
            return [(h["key"], h["value"]) for h in block["headers"]]
    return []


def render() -> str:
    lines = [
        "# GENERATED by tools/build-nginx.py from vercel.json — do not edit by hand.",
        "# Applied to Coolify app dozify-web via tools/deploy-nginx.sh.",
        "",
        "map $http_accept_language $dozify_home {",
        "    default /en;",
        "    ~*^tr /tr;",
        *[f"    ~*^{l} /{l};" for l in LANGS if has(l, "")],
        *(["    ~*^no /nb;"] if has("nb", "") else []),
        "}",
        "",
        "server {",
        "    listen 80;",
        "    server_name _;",
        "    root /usr/share/nginx/html;",
        "    index index.html;",
        "    absolute_redirect off;",
        "    server_tokens off;",
        "",
        "    # Coolify routes www and apex to this container without a redirect; one host only.",
        "    if ($host = www.dozify.app) { return 301 https://dozify.app$request_uri; }",
        "",
    ]
    for key, value in headers():
        lines.append(f'    add_header {key} "{value}" always;')
    lines += [
        '    add_header Strict-Transport-Security "max-age=31536000" always;',
        "",
        "    # Build inputs and notes are not part of the site.",
        "    location ~ ^/(tools|docs|deploy|\\.github)(/|$) { return 404; }",
        "    location ~ ^/(check\\.sh|vercel\\.json|\\.vercelignore|CNAME|README\\.md)$ { return 404; }",
        "    location ~* \\.(py|md|sh|json)$ { return 404; }",
        "",
        "    location = / { return 302 $dozify_home; }",
        "",
    ]
    for src, (dest, status) in exact_redirects().items():
        lines.append(f"    location = {src} {{ return {status} {dest}; }}")
    lines += [
        "",
        "    # Generated pages are linked without .html; send the .html form to the canonical URL.",
        "    location ~ ^(/.+)/index(\\.html)?$ { return 301 $1$is_args$args; }",
        "    location ~ ^(/.+)\\.html$ { return 301 $1$is_args$args; }",
        "    # No trailing slashes (canonicals have none).",
        "    location ~ ^(/.+)/$ { return 301 $1$is_args$args; }",
        "",
        "    location ~* \\.(css|js|png|jpg|jpeg|webp|svg|ico|woff2|mp4)$ {",
        "        expires 7d;",
        "        try_files $uri =404;",
        "    }",
        "",
        "    location / {",
        "        try_files $uri $uri.html $uri/index.html =404;",
        "    }",
        "",
        "    error_page 404 /404.html;",
        "    location = /404.html { internal; }",
        "}",
        "",
    ]
    return "\n".join(lines)


if __name__ == "__main__":
    OUT.parent.mkdir(exist_ok=True)
    text = render()
    OUT.write_text(text, encoding="utf-8")
    n = len(re.findall(r"location = ", text))
    print(f"{OUT.relative_to(ROOT)}: {n} exact locations, {len(headers())} headers")
